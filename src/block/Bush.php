declare(strict_types=1);

namespace pocketmine\block;

use pocketmine\block\utils\BlockEventHelper;
use pocketmine\item\Fertilizer;
use pocketmine\item\Item;
use pocketmine\math\Facing;
use pocketmine\math\Vector3;
use pocketmine\player\Player;

/** A ground bush which spreads to a supported neighboring air block with bone meal. */
class Bush extends Flower{
	public function canBeReplaced() : bool{
		return true;
	}

	public function onInteract(Item $item, int $face, Vector3 $clickVector, ?Player $player = null, array &$returnedItems = []) : bool{
		if($item instanceof Fertilizer){
			foreach(Facing::HORIZONTAL as $side){
				$target = $this->getSide($side);
				if($target instanceof Air && $this->canBePlacedAt($target, new Vector3(0, 0, 0), Facing::UP, false) && BlockEventHelper::grow($target, clone $this, $player)){
					$item->pop();
					return true;
				}
			}
		}
		return false;
	}
}
